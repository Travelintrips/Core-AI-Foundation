// ── Errors ────────────────────────────────────────────────────────────────────

export type DesignRenderErrorCode =
  | "UNSUPPORTED_FORMAT"
  | "UNSUPPORTED_ARTIFACT"
  | "RENDERER_UNAVAILABLE"
  | "RENDERER_CONFLICT"     // Duplicate renderer ID registration
  | "TENANT_MISMATCH"
  | "RESOURCE_LIMIT_EXCEEDED"
  | "FILENAME_UNSAFE"
  | "SIGNED_URL_EXPIRED"
  | "SIGNED_URL_INVALID"
  | "RENDER_TIMEOUT"
  | "RENDER_CANCELLED"
  | "RENDER_FAILED"
  | "PROFILE_INVALID"
  | "INPUT_VALIDATION_FAILED"
  | "UNKNOWN_ERROR";

export class DesignRenderError extends Error {
  readonly code: DesignRenderErrorCode;
  readonly retryable: boolean;
  readonly requestId?: string;
  readonly rendererId?: string;

  constructor(opts: {
    code: DesignRenderErrorCode;
    message: string;
    retryable?: boolean;
    requestId?: string;
    rendererId?: string;
  }) {
    super(opts.message);
    this.name = "DesignRenderError";
    this.code = opts.code;
    this.retryable = opts.retryable ?? NON_RETRYABLE_CODES.has(opts.code) === false;
    this.requestId = opts.requestId;
    this.rendererId = opts.rendererId;
  }

  toDescriptor(): {
    code: DesignRenderErrorCode;
    message: string;
    retryable: boolean;
    requestId?: string;
    rendererId?: string;
  } {
    return {
      code: this.code,
      message: this.message,
      retryable: this.retryable,
      requestId: this.requestId,
      rendererId: this.rendererId,
    };
  }
}

const NON_RETRYABLE_CODES = new Set<DesignRenderErrorCode>([
  "UNSUPPORTED_FORMAT",
  "UNSUPPORTED_ARTIFACT",
  "RENDERER_CONFLICT",
  "TENANT_MISMATCH",
  "FILENAME_UNSAFE",
  "SIGNED_URL_INVALID",
  "PROFILE_INVALID",
  "INPUT_VALIDATION_FAILED",
  "RENDER_CANCELLED",
]);

// ── Capability ────────────────────────────────────────────────────────────────

export interface DesignRenderCapability {
  /** Globally unique adapter identifier. */
  rendererId: string;
  /** Human-readable description for admin UI. */
  description: string;
  supportedFormats: DesignRenderFormat[];
  supportedTargets: DesignRenderTarget[];
  supportedArtifactKinds: string[];
  /** Maximum output width in pixels. */
  maxWidthPx: number;
  /** Maximum output height in pixels. */
  maxHeightPx: number;
  /** Maximum output file size in bytes (0 = no limit enforced by adapter). */
  maxFileSizeBytes: number;
  /** Wall-clock timeout in ms after which RENDER_TIMEOUT is raised. */
  timeoutMs: number;
  /** Whether a failed render with this adapter is worth retrying. */
  retryable: boolean;
  /**
   * Whether the adapter is currently operable.
   * A registry MUST NOT route to an unavailable adapter.
   */
  available: boolean;
  /** Required when available === false. */
  unavailableReason?: string;
  /**
   * Lower number = higher priority when multiple adapters match.
   * Deterministic: registry sorts ascending, then by rendererId for ties.
   */
  priority: number;
}

// ── Adapter interface ─────────────────────────────────────────────────────────

/**
 * All renderers implement this interface.
 *
 * Invariants:
 *  - render() must enforce tenant isolation (throw TENANT_MISMATCH if violated).
 *  - render() must sanitize output filenames.
 *  - render() must honour profile.maxFileSizeBytes.
 *  - render() must not load arbitrary modules at runtime.
 *  - canHandle() must be pure and synchronous.
 */
export interface DesignRendererAdapter {
  readonly rendererId: string;
  readonly capability: DesignRenderCapability;

  /** Synchronous eligibility check — called by registry during resolution. */
  canHandle(request: DesignRenderRequest): boolean;

  /** Execute the render. Must complete within capability.timeoutMs. */
  render(request: DesignRenderRequest): Promise<DesignRenderResult>;
}

// ── Filename safety ───────────────────────────────────────────────────────────

/**
 * Sanitize a filename component so it is safe for use in storage paths.
 * Strips path traversal, null bytes, and non-printable characters.
 * Returns a non-empty string or throws DesignRenderError(FILENAME_UNSAFE).
 */
export function sanitizeRenderFilename(raw: string): string {
  // Remove path separators, null bytes, control chars, and dangerous sequences
  const cleaned = raw
    .replace(/[/\\]/g, "_")          // No path separators
    .replace(/\.\./g, "_")           // No parent-dir traversal
    .replace(/\x00/g, "")           // No null bytes
    .replace(/[^\x20-\x7E]/g, "_")  // ASCII printable only
    .replace(/^\.+/, "_")           // No leading dots (hidden files)
    .trim()
    .slice(0, 200);                  // Reasonable length cap

  if (!cleaned || cleaned.replace(/_/g, "").length === 0) {
    throw new DesignRenderError({
      code: "FILENAME_UNSAFE",
      message: `Filename "${raw}" is not safe for storage use`,
      retryable: false,
    });
  }
  return cleaned;
}

// ── Signed URL ────────────────────────────────────────────────────────────────

const SIGNED_URL_SECRET =
  process.env["SESSION_SECRET"] ?? process.env["ADMIN_API_KEY"] ?? "dev-only-insecure-secret";

const SIGNED_URL_TTL_SECONDS = 3600; // 1 hour default

interface RenderSignedPayload {
  id: string;
  tenantId: string;
  storagePath: string;
  exp: number;
}

/**
 * Generate a short-lived, HMAC-signed URL token for a rendered output.
 * The storagePath MUST NOT be embedded verbatim in API responses —
 * only the signed token should be exposed to clients.
 */
export function generateRenderSignedToken(
  tenantId: string,
  storagePath: string,
  ttlSeconds = SIGNED_URL_TTL_SECONDS,
): { token: string; expiresAt: string } {
  const payload: RenderSignedPayload = {
    id: randomBytes(8).toString("hex"),
    tenantId,
    storagePath,
    exp: Math.floor(Date.now() / 1000) + ttlSeconds,
  };
  const encoded = Buffer.from(JSON.stringify(payload)).toString("base64url");
  const sig = createHmac("sha256", SIGNED_URL_SECRET).update(encoded).digest("base64url");
  const token = `${encoded}.${sig}`;
  const expiresAt = new Date((payload.exp) * 1000).toISOString();
  return { token, expiresAt };
}

export interface RenderSignedTokenVerifyResult {
  valid: boolean;
  tenantId?: string;
  storagePath?: string;
  reason?: string;
}

/**
 * Verify a render signed token.
 * Returns { valid: false } for malformed, tampered, or expired tokens.
 * Callers MUST check tenantId matches the requesting tenant.
 */
export function verifyRenderSignedToken(token: string): RenderSignedTokenVerifyResult {
  const parts = token.split(".");
  if (parts.length !== 2) return { valid: false, reason: "Malformed token" };

  const [encoded, sig] = parts as [string, string];
  const expectedSig = createHmac("sha256", SIGNED_URL_SECRET).update(encoded).digest("base64url");
  if (sig !== expectedSig) return { valid: false, reason: "Invalid signature" };

  let payload: RenderSignedPayload;
  try {
    payload = JSON.parse(Buffer.from(encoded, "base64url").toString("utf8")) as RenderSignedPayload;
  } catch {
    return { valid: false, reason: "Payload parse error" };
  }

  if (Math.floor(Date.now() / 1000) > payload.exp) {
    return { valid: false, reason: "Token expired" };
  }
  return { valid: true, tenantId: payload.tenantId, storagePath: payload.storagePath };
}

