/**
 * Team 32 — Design Rendering and Preview Adapters
 *
 * Contract types for the universal adapter layer between design artifacts
 * and the renderer/preview engines.
 *
 * Design principles:
 *  - Every render result carries an honest classification (see RenderClassification).
 *  - No renderer claims 3D capability if a 3D engine is unavailable.
 *  - Tenant isolation is a first-class invariant, not an afterthought.
 *  - Signed URLs are mandatory for any result that references object storage.
 *  - Filenames are always sanitized before reaching storage paths.
 */

import { createHmac, randomBytes } from "crypto";

// ── Formats ───────────────────────────────────────────────────────────────────

export type DesignRenderFormat =
  | "png"
  | "jpg"
  | "webp"
  | "pdf"
  | "pdf-print"
  | "svg"
  | "thumbnail"
  | "zip"
  | "composition";

export const SUPPORTED_FORMATS: ReadonlySet<DesignRenderFormat> = new Set([
  "png", "jpg", "webp", "pdf", "pdf-print", "svg", "thumbnail", "zip", "composition",
]);

// ── Render targets ────────────────────────────────────────────────────────────

/**
 * What the output will be used for.
 * This drives profile selection and honest classification.
 */
export type DesignRenderTarget =
  | "artifact_preview"     // Card / gallery preview of an artifact
  | "thumbnail"            // Small thumbnail (≤ 512 px on the long edge)
  | "workspace_image"      // Full workspace view (customer portal)
  | "review_preview"       // Review/approval lightbox
  | "document_page"        // A page from a document (PDF / DOCX)
  | "presentation_slide"   // A slide from a presentation
  | "technical_preview"    // Internal QA / admin preview
  | "mockup_preview"       // Mockup sandbox component preview
  | "3d_preview_placeholder"; // 3D artifact — no native 3D engine available

// ── Honesty classification ────────────────────────────────────────────────────

/**
 * Every render result MUST carry one of these labels.
 * Callers must expose this to users where the fidelity matters
 * (e.g. "PDF Preview" vs "Converted PDF").
 */
export type RenderClassification =
  | "native_conversion"       // Format-native output from a real converter (e.g. SVG→PDF)
  | "rasterized_preview"      // Rasterized from a vector/document source (e.g. PDF→PNG)
  | "spec_rendered"           // Built from a design spec (SVG pipeline → PNG/PDF)
  | "generated_approximation" // AI-generated visual approximation of the artifact
  | "unavailable"             // No renderer can handle this request
  | "placeholder";            // A generic placeholder image was returned

// ── Render profile ────────────────────────────────────────────────────────────

/**
 * Describes the desired output characteristics.
 * Renderers MUST NOT ignore maxFileSizeBytes, nor force high resolution
 * on every request.
 */
export interface DesignRenderProfile {
  /** Output pixel width. */
  widthPx: number;
  /** Output pixel height. */
  heightPx: number;
  /** Device pixel ratio for HiDPI outputs (default 1). */
  pixelRatio?: number;
  /** JPEG/WebP quality 0-100 (default 85 for full, 70 for preview). */
  quality?: number;
  /** CSS color string for the background, or "transparent". */
  background?: string;
  /** When true, output must support alpha transparency. */
  transparent?: boolean;
  /** Requested output format. */
  format: DesignRenderFormat;
  /** 1-based page index for multi-page documents. */
  page?: number;
  /** 1-based frame index for animated sources. */
  frame?: number;
  /** ICC color profile hint ("srgb" | "display-p3"). */
  colorProfile?: string;
  /** How the output will be used — drives renderer selection. */
  purpose: DesignRenderTarget;
  /** Hard cap on output file size. Renderer must reject if exceeded. */
  maxFileSizeBytes?: number;
  /**
   * true → lower resolution / quality is acceptable (preview).
   * false → full production quality.
   */
  previewQuality: boolean;
}

// ── Render request ────────────────────────────────────────────────────────────

export interface DesignRenderRequest {
  /** Stable unique ID for idempotency; generated by caller or registry. */
  requestId?: string;
  /** Tenant scope — MUST be validated server-side; never trust client input. */
  tenantId: string;
  /**
   * Kind of artifact being rendered.
   * Determines which adapter family is eligible.
   * Examples: "design_template", "document", "presentation", "image".
   */
  artifactKind: string;
  /** Artifact identifier (template ID, document ID, etc.). */
  artifactId: string;
  /** Desired output profile. */
  profile: DesignRenderProfile;
  /**
   * Variable data / row data for template-based renders.
   * Adapters must validate this against the artifact's schema.
   */
  sourceData?: Record<string, unknown>;
}

