#!/usr/bin/env bash
# Narrow synthetic lock prototype; deliberately NOT a deployable review issuer.
set -euo pipefail
cd "$(dirname "$0")/../.."
name="gpt02-atomic-prototype-$$"
work="$(mktemp -d /tmp/gpt02-atomic-proto.XXXXXX)"
cleanup(){ docker rm -f "$name" >/dev/null 2>&1 || :; rm -rf "$work"; }
trap cleanup EXIT
docker run -d --name "$name" --network none --tmpfs /var/lib/postgresql/data:rw,size=128m -e POSTGRES_HOST_AUTH_METHOD=trust postgres:16-alpine >/dev/null
for i in $(seq 1 40); do
  if docker exec "$name" pg_isready -q -U postgres && docker exec "$name" psql -U postgres -qAt -c 'SELECT 1' 2>/dev/null | grep -qx 1; then break; fi
  sleep 1
done
docker exec -i "$name" psql -U postgres -v ON_ERROR_STOP=1 -q <<'SQL'
CREATE ROLE gpt02_dev_review_writer NOLOGIN NOINHERIT NOBYPASSRLS;
CREATE ROLE aicore_dev_runtime NOLOGIN;
CREATE ROLE anon NOLOGIN;
CREATE SCHEMA ai_platform;
GRANT USAGE ON SCHEMA ai_platform TO gpt02_dev_review_writer,aicore_dev_runtime;
CREATE TABLE ai_platform.ai_coding_bridge_commands(id integer PRIMARY KEY,status text NOT NULL);
CREATE TABLE ai_platform.dev_review_synthetic(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,command_id integer NOT NULL,nonce text UNIQUE NOT NULL);
INSERT INTO ai_platform.ai_coding_bridge_commands VALUES(1,'PROCESSING');
ALTER TABLE ai_platform.dev_review_synthetic ENABLE ROW LEVEL SECURITY;
CREATE POLICY synthetic_read ON ai_platform.dev_review_synthetic FOR SELECT TO gpt02_dev_review_writer USING(true);
GRANT SELECT ON ai_platform.dev_review_synthetic TO gpt02_dev_review_writer;
-- Security-definer prototype with intentionally limited parameters.
-- NOT secure for real signatures/authorization; not deployed.
CREATE FUNCTION ai_platform._synthetic_lock_then_append(p_command integer,p_nonce text)
RETURNS integer LANGUAGE plpgsql SECURITY DEFINER
SET search_path=pg_catalog,ai_platform AS $$
DECLARE cur_status text;
DECLARE new_id integer;
BEGIN
 SELECT status INTO cur_status FROM ai_platform.ai_coding_bridge_commands
  WHERE id=p_command FOR UPDATE;
 IF cur_status IS DISTINCT FROM 'PROCESSING' THEN RETURN NULL; END IF;
 INSERT INTO ai_platform.dev_review_synthetic(command_id,nonce)
 VALUES(p_command,p_nonce) RETURNING id INTO new_id;
 RETURN new_id;
END $$;
REVOKE ALL ON FUNCTION ai_platform._synthetic_lock_then_append(integer,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION ai_platform._synthetic_lock_then_append(integer,text) TO gpt02_dev_review_writer;
SQL
rights="$(docker exec "$name" psql -U postgres -qAt -c "SELECT has_function_privilege('aicore_dev_runtime','ai_platform._synthetic_lock_then_append(integer,text)','EXECUTE'),has_function_privilege('gpt02_dev_review_writer','ai_platform._synthetic_lock_then_append(integer,text)','EXECUTE'),has_table_privilege('gpt02_dev_review_writer','ai_platform.ai_coding_bridge_commands','UPDATE'),has_table_privilege('gpt02_dev_review_writer','ai_platform.dev_review_synthetic','INSERT');")"
[ "$rights" = "f|t|f|f" ] || { echo "FAIL capability separation: $rights";exit 1; }
echo "CAPABILITY SCOPING PASS"
if docker exec "$name" psql -U postgres -v ON_ERROR_STOP=1 -q -c "SET ROLE aicore_dev_runtime; SELECT ai_platform._synthetic_lock_then_append(1,'forbidden')" >/dev/null 2>&1; then
 echo "FAIL ordinary runtime executed writer"; exit 1
fi
echo "ORDINARY RUNTIME CANNOT EXECUTE PASS"
# Hold a terminal status update while the reviewer attempts the locked append.
cat > "$work/status.sql" <<'SQL'
BEGIN;
UPDATE ai_platform.ai_coding_bridge_commands SET status='FAILED' WHERE id=1;
SELECT pg_sleep(2);
COMMIT;
SQL
docker exec -i "$name" psql -U postgres -v ON_ERROR_STOP=1 -q < "$work/status.sql" > "$work/status.log" 2>&1 &
a=$!
sleep 0.4
docker exec "$name" psql -U postgres -v ON_ERROR_STOP=1 -qAt -c "SET ROLE gpt02_dev_review_writer; SELECT coalesce(ai_platform._synthetic_lock_then_append(1,'race-1')::text,'blocked')" > "$work/after.log" 2>&1 &
b=$!
wait "$a";wait "$b"
[ "$(tail -n 1 "$work/after.log")" = blocked ] || { cat "$work/after.log";echo 'FAIL terminal-first race';exit 1; }
[ "$(docker exec "$name" psql -U postgres -qAt -c 'SELECT count(*) FROM ai_platform.dev_review_synthetic')" = 0 ] || { echo 'FAIL terminal-first inserted';exit 1; }
echo "TERMINAL BEFORE APPEND PASS"
docker exec "$name" psql -U postgres -v ON_ERROR_STOP=1 -q -c "UPDATE ai_platform.ai_coding_bridge_commands SET status='PROCESSING' WHERE id=1" >/dev/null
cat > "$work/append.sql" <<'SQL'
BEGIN;
SET ROLE gpt02_dev_review_writer;
SELECT ai_platform._synthetic_lock_then_append(1,'race-2');
SELECT pg_sleep(2);
COMMIT;
SQL
docker exec -i "$name" psql -U postgres -v ON_ERROR_STOP=1 -q < "$work/append.sql" > "$work/append.log" 2>&1 &
a=$!
sleep 0.5
docker exec "$name" psql -U postgres -v ON_ERROR_STOP=1 -q -c "SET lock_timeout='5s'; UPDATE ai_platform.ai_coding_bridge_commands SET status='FAILED' WHERE id=1" > "$work/terminal-after.log" 2>&1 &
b=$!
wait "$a";wait "$b"
state="$(docker exec "$name" psql -U postgres -qAt -c 'SELECT (SELECT count(*) FROM ai_platform.dev_review_synthetic),(SELECT status FROM ai_platform.ai_coding_bridge_commands WHERE id=1)')"
[ "$state" = '1|FAILED' ] || { echo "FAIL append-first: $state";exit 1; }
echo "APPEND FIRST THEN TERMINAL PASS (historical only, never a grant)"
if docker exec "$name" psql -U postgres -v ON_ERROR_STOP=1 -q -c "SET ROLE gpt02_dev_review_writer; UPDATE ai_platform.ai_coding_bridge_commands SET status='PROCESSING' WHERE id=1" >/dev/null 2>&1; then
 echo "FAIL writer changed command";exit 1
fi
echo "WRITER CANNOT ALTER COMMAND PASS"
echo "ATOMIC LOCK PROTOTYPE PASS — synthetic only; no signature checks, no trusted issuer"
