#!/usr/bin/env python3
"""Issue159 postlineage read-identity proposal, signed fixture only.

No operational credential, private key from VPS, database, or socket.
Four ephemeral test signers are generated by the existing fixture.
"""
from __future__ import annotations
import copy
import hashlib
import json
import unittest
from unittest.mock import patch

import gpt02_issue159_positive_permit_handoff as handoff
from gpt02_issue159_writer_broker_contract import (
    BrokerAdmissionError, verify_lifecycle_evidence_packet,
)
from test_gpt02_issue159_writer_broker_contract import WriterBrokerContractTest


class PostlineageReaderScopeOfflineTest(unittest.TestCase):
    def setUp(self):
        f = WriterBrokerContractTest(
            methodName="test_four_domain_signatures_verify_but_no_authority"
        )
        f.setUp()
        self.fixture = f
        verified = verify_lifecycle_evidence_packet(f.packet, f.roots, f.now)
        packet = json.dumps(
            f.packet, sort_keys=True, ensure_ascii=False,
            separators=(",", ":"), allow_nan=False,
        ).encode()
        self.proof = {
            "environment": "DEV",
            "stage": "FOUR_SIGNATURE_PERSISTED_LINEAGE_REVIEWED",
            "hubTaskId": f.approval["taskId"],
            "commandId": f.approval["commandId"],
            "attemptId": f.approval["attemptId"],
            "fenceId": f.issuer["fenceId"],
            "verifiedPacketSha256": hashlib.sha256(packet).hexdigest(),
            "approvalDigest": verified["approvalDigest"],
            "hubLinkDigest": verified["hubLinkDigest"],
            "coreLinkDigest": verified["coreLinkDigest"],
            "verifiedByExistingReader": True,
            "positivePermitCreated": False,
            "databaseWritePerformed": False,
            "signingPermitted": False,
            "authorizationGranted": False,
            "dispatchPermitted": False,
            "releaseDecision": "NO_GO",
        }

    def check(self, *, packet=None, proof=None, now=None):
        f = self.fixture
        if packet is None:
            packet = f.packet
        if proof is None:
            proof = self.proof
        if now is None:
            now = f.now
        with patch.object(
            handoff, "inspect_proposed_permit_candidate", return_value=proof
        ) as inspector:
            with patch.object(handoff.time, "time", return_value=now/1000):
                result = handoff.inspect_postlineage_scoped_reader_candidate(
                    packet, f.roots
                )
        inspector.assert_called_once_with(packet, f.roots)
        return result

    def test_exact_signed_receipt_fence_and_all_scope_fields(self):
        f = self.fixture
        result = self.check()
        scope = result["scope"]
        self.assertEqual(scope["company_id"], "default")
        self.assertEqual(scope["task_id"], f.approval["taskId"])
        self.assertEqual(scope["command_id"], f.approval["commandId"])
        self.assertEqual(scope["attempt_id"], f.approval["attemptId"])
        self.assertEqual(scope["approval_digest"], f.issuer["approvalDigest"])
        self.assertEqual(scope["approval_nonce"], f.approval["nonce"])
        self.assertEqual(scope["link_id"], f.link["linkId"])
        self.assertEqual(scope["hub_execution_id"], f.link["hubExecutionId"])
        self.assertEqual(scope["core_task_id"], f.link["coreTaskId"])
        self.assertEqual(scope["receipt_id"], f.issuer["receiptId"])
        self.assertEqual(scope["fence_id"], f.issuer["fenceId"])
        self.assertEqual(scope["lease_epoch"], 1)
        self.assertRegex(result["candidateRole"], r"^dev_gpt02_task_140_[0-9a-f]{12}$")
        self.assertRegex(result["scopeSha256"], r"^[a-f0-9]{64}$")
        self.assertEqual(result["expiresAt"], f.issuer["expiresAt"])
        self.assertTrue(result["persistedLineageMatched"])
        self.assertTrue(result["persistedAdminApprovalReadBack"])
        for name in ("databaseRoleProvisioned", "credentialIssuancePermitted",
                     "databaseWritePerformed", "signingPermitted",
                     "authorizationGranted", "dispatchPermitted"):
            self.assertIs(result[name], False)
        self.assertEqual(result["releaseDecision"], "NO_GO")

    def test_repeat_signed_packet_never_mints_access(self):
        first = self.check()
        second = self.check()
        self.assertEqual(first["scopeSha256"], second["scopeSha256"])
        self.assertEqual(first["candidateRole"], second["candidateRole"])
        self.assertFalse(first["credentialIssuancePermitted"])
        self.assertFalse(second["credentialIssuancePermitted"])

    def test_modified_receipt_id_rejected_even_with_old_trusted_response(self):
        packet = copy.deepcopy(self.fixture.packet)
        packet["issuerEvidence"]["claims"]["receiptId"] = (
            "69999999-9999-4999-8999-999999999999"
        )
        with self.assertRaises(BrokerAdmissionError):
            self.check(packet=packet)

    def test_modified_link_id_rejected_even_with_old_trusted_response(self):
        packet = copy.deepcopy(self.fixture.packet)
        packet["hubLink"]["claims"]["linkId"] = (
            "39999999-9999-4999-8999-999999999999"
        )
        with self.assertRaises(BrokerAdmissionError):
            self.check(packet=packet)

    def test_mismatched_response_digest_or_packet_sha_denied(self):
        for field, value in (
            ("approvalDigest", "f" * 64),
            ("hubLinkDigest", "f" * 64),
            ("coreLinkDigest", "f" * 64),
            ("verifiedPacketSha256", "f" * 64),
        ):
            with self.subTest(field=field):
                p = dict(self.proof)
                p[field] = value
                with self.assertRaises(BrokerAdmissionError):
                    self.check(proof=p)

    def test_expiring_issuer_fails_after_authenticated_readback(self):
        with self.assertRaisesRegex(
            BrokerAdmissionError, "POSTLINEAGE_LEASE_TOO_CLOSE_TO_EXPIRY"
        ):
            self.check(now=self.fixture.now+2000)

    def test_missing_trusted_readback_never_constructs_role(self):
        for field, value in (
            ("verifiedByExistingReader", False),
            ("releaseDecision", "GO"),
            ("positivePermitCreated", True),
            ("signingPermitted", True),
            ("stage", "DISPATCH_GRANTED"),
        ):
            with self.subTest(field=field):
                p = dict(self.proof)
                p[field] = value
                with self.assertRaises(BrokerAdmissionError):
                    self.check(proof=p)

    def test_no_caller_supplied_role_or_task_override(self):
        with self.assertRaises(TypeError):
            handoff.inspect_postlineage_scoped_reader_candidate(
                self.fixture.packet, self.fixture.roots,
                task_id=172,
                role="service_role"
            )


if __name__ == "__main__":
    unittest.main()
